function snapshot(text: string): string {
  return text.replace(/^\n/, '');
}

const TOP_H = STRIP_HEIGHTS.top;
const BOTTOM_H = STRIP_HEIGHTS.bottom;

function at(frame: Uint8Array, x: number, y: number): number {
  return frame[y * STRIP_WIDTH + x] as number;
}

/** Levels a filled area may hold: one for a solid paint, two for a checker. */
function levelsOf(paint: number | { on: number; off: number }): Set<number> {
  return new Set<number>(
    typeof paint === 'number' ? [paint] : [paint.on, paint.off],
  );
}
