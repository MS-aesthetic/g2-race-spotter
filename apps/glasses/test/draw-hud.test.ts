function snapshot(text: string): string {
  return text.replace(/^\n/, '');
}

function at(frame: Uint8Array, x: number, y: number): number {
  return frame[y * HUD_WIDTH + x] as number;
}

/** Levels a dithered area may hold: the checker's two phases. */
const FILL_LEVELS = new Set<number>([DESIGN.fill.on, DESIGN.fill.off]);
const ALERT_FILL_LEVELS = new Set<number>([
  DESIGN.alertFill.on,
  DESIGN.alertFill.off,
]);

describe('drawHud', () => {
  it('fills exactly 288x144 bytes of 0..15', () => {
    const frame = drawHud(
      { lane: 'mid', side: null, gap: 62 },
      { linkOk: true },
    );

    expect(frame).toBeInstanceOf(Uint8Array);
    expect(frame.length).toBe(HUD_WIDTH * HUD_HEIGHT);
    expect(Math.max(...frame)).toBeLessThanOrEqual(15);
  });

  it('draws the up triangle on the right for top/50', () => {
    expect(
      toAscii(drawHud({ lane: 'top', side: null, gap: 50 }, { linkOk: true })),
    ).toBe(snapshot(GOLDEN_TOP_50));
  });

  it('draws the disc in the middle and a left arrow for mid/62/inside', () => {
    expect(
      toAscii(
        drawHud({ lane: 'mid', side: 'inside', gap: 62 }, { linkOk: true }),
      ),
    ).toBe(snapshot(GOLDEN_MID_62_INSIDE));
  });

  it('draws the down triangle on the left, the alert bar and a right arrow for bot/95/outside', () => {
    expect(
      toAscii(
        drawHud({ lane: 'bot', side: 'outside', gap: 95 }, { linkOk: true }),
      ),
    ).toBe(snapshot(GOLDEN_BOT_95_OUTSIDE));
  });

  it('draws the down triangle and a left arrow for bot/40/inside', () => {
    expect(
      toAscii(
        drawHud({ lane: 'bot', side: 'inside', gap: 40 }, { linkOk: true }),
      ),
    ).toBe(snapshot(GOLDEN_BOT_40_INSIDE));
  });

  it('draws three lane outlines, the bar and ticks for null/0', () => {
    expect(
      toAscii(drawHud({ lane: null, side: null, gap: 0 }, { linkOk: true })),
    ).toBe(snapshot(GOLDEN_NULL_0));
  });

  it('renders the stale variant as every pixel >> 1 (050 AC-2)', () => {
    const bright = drawHud(
      { lane: 'top', side: null, gap: 50 },
      { linkOk: true },
    );
    const dimmed = drawHud(
      { lane: 'top', side: null, gap: 50 },
      { linkOk: false },
    );

    expect(dimmed.length).toBe(bright.length);
    for (let index = 0; index < bright.length; index += 1) {
      expect(dimmed[index]).toBe((bright[index] as number) >> 1);
    }
    expect(toAscii(dimmed)).toBe(snapshot(GOLDEN_TOP_50_DIM));
  });

  it('dithers every filled area and nothing else', () => {
    // `min` sampling drops solid edges to `.` and leaves dithered areas at `+`,
    // so this golden is the map of what the driver sees as a half tone: the
    // called lane, the bar fill and the side arrow.
    expect(
      toAscii(
        drawHud({ lane: 'mid', side: 'inside', gap: 62 }, { linkOk: true }),
        { sample: 'min' },
      ),
    ).toBe(snapshot(GOLDEN_MID_62_INSIDE_DITHER));
  });

  it('fills the called lane with a 2x2 checker on the pixel grid', () => {
    const frame = drawHud(
      { lane: 'mid', side: null, gap: 0 },
      { linkOk: true },
    );
    const centre = {
      x: 144,
      y: (DESIGN.lanes.topY + DESIGN.lanes.bottomY) / 2,
    };

    // Neighbouring pixels alternate: that is the dither, not an average level.
    expect(at(frame, centre.x, centre.y)).toBe(DESIGN.fill.on);
    expect(at(frame, centre.x + 1, centre.y)).toBe(DESIGN.fill.off);
    expect(at(frame, centre.x, centre.y + 1)).toBe(DESIGN.fill.off);
    expect(at(frame, centre.x + 1, centre.y + 1)).toBe(DESIGN.fill.on);
  });

  it('keeps the two uncalled lanes as hollow outlines (050 AC-1)', () => {
    const frame = drawHud(
      { lane: 'mid', side: null, gap: 0 },
      { linkOk: true },
    );
    const { outlineLevel, bottomY, topY } = DESIGN.lanes;

    // ▲ on the right: base edge lit, interior empty.
    expect(at(frame, 240, bottomY - 1)).toBe(outlineLevel);
    expect(at(frame, 240, bottomY - 2)).toBe(0);
    // ▼ on the left: top edge lit, interior empty.
    expect(at(frame, 48, topY)).toBe(outlineLevel);
    expect(at(frame, 48, topY + 14)).toBe(0);
    // The called lane is the only filled one.
    expect(at(frame, 144, 36)).toBe(DESIGN.fill.on);
  });

  it('puts the lanes in track order: bot left, mid middle, top right', () => {
    expect(DESIGN.lanes.slots.map((slot) => slot.lane)).toEqual([
      'bot',
      'mid',
      'top',
    ]);
    expect(DESIGN.lanes.slots.map((slot) => slot.centreX)).toEqual([
      48, 144, 240,
    ]);

    // Each call lights its own slot and no other.
    const bot = drawHud({ lane: 'bot', side: null, gap: 0 }, { linkOk: true });
    const top = drawHud({ lane: 'top', side: null, gap: 0 }, { linkOk: true });
    expect(FILL_LEVELS.has(at(bot, 48, 20))).toBe(true);
    expect(at(bot, 240, 60)).toBe(0);
    expect(FILL_LEVELS.has(at(top, 240, 60))).toBe(true);
    expect(at(top, 48, 20)).toBe(0);
  });

  it('shows a side arrow only on the side the car is on', () => {
    const inside = drawHud(
      { lane: null, side: 'inside', gap: 0 },
      { linkOk: true },
    );
    const outside = drawHud(
      { lane: null, side: 'outside', gap: 0 },
      { linkOk: true },
    );
    const clear = drawHud({ lane: null, side: null, gap: 0 }, { linkOk: true });
    const midY = DESIGN.side.y + DESIGN.side.height / 2;
    const left = DESIGN.side.margin + 6;
    const right = HUD_WIDTH - 1 - DESIGN.side.margin - 6;

    expect(FILL_LEVELS.has(at(inside, left, midY))).toBe(true);
    expect(at(inside, right, midY)).toBe(0);
    expect(FILL_LEVELS.has(at(outside, right, midY))).toBe(true);
    expect(at(outside, left, midY)).toBe(0);
    expect(at(clear, left, midY)).toBe(0);
    expect(at(clear, right, midY)).toBe(0);
  });

  it('inverts the bar at gap >= 90 (050 AC-2)', () => {
    const { bar } = DESIGN;
    const normal = drawHud(
      { lane: null, side: null, gap: 50 },
      { linkOk: true },
    );
    const alert = drawHud(
      { lane: null, side: null, gap: 95 },
      { linkOk: true },
    );
    // A pixel on the top outline, clear of the fill, and one inside the fill.
    const inside = { x: bar.x + bar.fillInset + 2, y: bar.fillY + 2 };

    expect(at(normal, bar.x + 20, bar.y)).toBe(bar.outlineLevel);
    expect(at(alert, bar.x + 20, bar.y)).toBe(bar.alertOutlineLevel);
    expect(FILL_LEVELS.has(at(normal, inside.x, inside.y))).toBe(true);
    expect(ALERT_FILL_LEVELS.has(at(alert, inside.x, inside.y))).toBe(true);
  });

  it('scales the bar fill with gap and stops the ticks at the fill edge', () => {
    const { bar } = DESIGN;
    const y = bar.fillY + 2;
    const empty = drawHud({ lane: null, side: null, gap: 0 }, { linkOk: true });
    const half = drawHud({ lane: null, side: null, gap: 50 }, { linkOk: true });
    const full = drawHud(
      { lane: null, side: null, gap: 100 },
      { linkOk: true },
    );

    const filled = (frame: Uint8Array, levels: Set<number>): number => {
      let count = 0;
      for (let x = bar.fillInset; x < bar.width - bar.fillInset; x += 1) {
        if (levels.has(at(frame, x, y))) {
          count += 1;
        }
      }
      return count;
    };

    expect(filled(empty, FILL_LEVELS)).toBe(0);
    expect(filled(half, FILL_LEVELS)).toBe(141);
    // gap 100 is above the alert threshold, so the full bar is the dimmer fill.
    expect(filled(full, ALERT_FILL_LEVELS)).toBe(282);
    // Tick at x=72 is inside the half-full bar, so it must not punch a hole.
    expect(FILL_LEVELS.has(at(half, 72, y))).toBe(true);
    expect(at(empty, 72, y)).toBe(bar.tickLevel);
  });
});
