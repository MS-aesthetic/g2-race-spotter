function snapshot(text: string): string {
  return text.replace(/^\n/, '');
}

describe('drawHud', () => {
  it('fills exactly 288x144 bytes of 0..15', () => {
    const frame = drawHud({ lane: 'mid', gap: 62 }, { linkOk: true });

    expect(frame).toBeInstanceOf(Uint8Array);
    expect(frame.length).toBe(HUD_WIDTH * HUD_HEIGHT);
    expect(Math.max(...frame)).toBeLessThanOrEqual(15);
  });

  it('draws the up triangle and a half-full bar for top/50', () => {
    expect(toAscii(drawHud({ lane: 'top', gap: 50 }, { linkOk: true }))).toBe(
      snapshot(GOLDEN_TOP_50),
    );
  });

  it('draws the disc for mid/62', () => {
    expect(toAscii(drawHud({ lane: 'mid', gap: 62 }, { linkOk: true }))).toBe(
      snapshot(GOLDEN_MID_62),
    );
  });

  it('draws the down triangle and the alert bar for bot/95', () => {
    expect(toAscii(drawHud({ lane: 'bot', gap: 95 }, { linkOk: true }))).toBe(
      snapshot(GOLDEN_BOT_95),
    );
  });

  it('draws bar and ticks only for null/0', () => {
    expect(toAscii(drawHud({ lane: null, gap: 0 }, { linkOk: true }))).toBe(
      snapshot(GOLDEN_NULL_0),
    );
  });

  it('renders the stale variant as every pixel >> 1 (050 AC-2)', () => {
    const bright = drawHud({ lane: 'top', gap: 50 }, { linkOk: true });
    const dimmed = drawHud({ lane: 'top', gap: 50 }, { linkOk: false });

    expect(dimmed.length).toBe(bright.length);
    for (let index = 0; index < bright.length; index += 1) {
      expect(dimmed[index]).toBe((bright[index] as number) >> 1);
    }
    expect(toAscii(dimmed)).toBe(snapshot(GOLDEN_TOP_50_DIM));
  });

  it('inverts the bar at gap >= 90 (050 AC-2)', () => {
    const { bar } = DESIGN;
    const normal = drawHud({ lane: null, gap: 50 }, { linkOk: true });
    const alert = drawHud({ lane: null, gap: 95 }, { linkOk: true });
    // A pixel on the top outline, clear of the fill, and one inside the fill.
    const outline = bar.y * HUD_WIDTH + bar.x + 20;
    const inside = (bar.fillY + 2) * HUD_WIDTH + bar.x + bar.fillInset + 2;

    expect(normal[outline]).toBe(bar.outlineLevel);
    expect(alert[outline]).toBe(bar.alertOutlineLevel);
    expect(normal[inside]).toBe(bar.fillLevel);
    expect(alert[inside]).toBe(bar.alertFillLevel);
  });

  it('scales the bar fill with gap and stops the ticks at the fill edge', () => {
    const { bar } = DESIGN;
    const row = (bar.fillY + 2) * HUD_WIDTH;
    const empty = drawHud({ lane: null, gap: 0 }, { linkOk: true });
    const half = drawHud({ lane: null, gap: 50 }, { linkOk: true });
    const full = drawHud({ lane: null, gap: 100 }, { linkOk: true });

    const filled = (frame: Uint8Array, level: number): number => {
      let count = 0;
      for (let x = bar.fillInset; x < bar.width - bar.fillInset; x += 1) {
        if (frame[row + x] === level) {
          count += 1;
        }
      }
      return count;
    };

    expect(filled(empty, bar.fillLevel)).toBe(0);
    expect(filled(half, bar.fillLevel)).toBe(141);
    // gap 100 is above the alert threshold, so the full bar is the dimmer fill.
    expect(filled(full, bar.alertFillLevel)).toBe(282);
    // Tick at x=72 is inside the half-full bar, so it must not punch a hole.
    expect(half[row + 72]).toBe(bar.fillLevel);
    expect(empty[row + 72]).toBe(bar.tickLevel);
  });
});
