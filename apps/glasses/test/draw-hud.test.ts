function snapshot(text: string): string {
  return text.replace(/^\n/, '');
}

function at(frame: Uint8Array, x: number, y: number): number {
  return frame[y * HUD_WIDTH + x] as number;
}

/** Levels a dithered area may hold: the checker's two phases. */
const FILL_LEVELS = new Set<number>([DESIGN.fill.on, DESIGN.fill.off]);
const ALERT_FILL_LEVELS = new Set<number>([
  DESIGN.alertFill.on,
  DESIGN.alertFill.off,
]);

const { cars: BAR, lanes: LANES } = DESIGN;
/** A pixel in the middle of segment `cell` (0..2) of the bar at `barX`. */
function segmentCentre(
  barX: number,
  cell: number,
): { readonly x: number; readonly y: number } {
  const wall = BAR.outlineThickness;
  return {
    x:
      barX +
      wall +
      cell * (BAR.segmentWidth + wall) +
      Math.floor(BAR.segmentWidth / 2),
    y: BAR.y + Math.floor(BAR.height / 2),
  };
}

describe('drawHud', () => {
  it('fills exactly 288x144 bytes of 0..15', () => {
    const frame = drawHud({ lane: 'mid', cars: [1, 2, 3] }, { linkOk: true });

    expect(frame).toBeInstanceOf(Uint8Array);
    expect(frame.length).toBe(HUD_WIDTH * HUD_HEIGHT);
    expect(Math.max(...frame)).toBeLessThanOrEqual(15);
  });

  it('draws ▲ on the right and bars 1 / 2 / 3 for top, [1, 2, 3]', () => {
    expect(
      toAscii(drawHud({ lane: 'top', cars: [1, 2, 3] }, { linkOk: true })),
    ).toBe(snapshot(GOLDEN_TOP_123));
  });

  it('draws the dash in the middle and three empty bars for mid, [0, 0, 0]', () => {
    expect(
      toAscii(drawHud({ lane: 'mid', cars: [0, 0, 0] }, { linkOk: true })),
    ).toBe(snapshot(GOLDEN_MID_000));
  });

  it('draws ▼ on the left and a full alert bar on the left for bot, [3, 0, 0]', () => {
    expect(
      toAscii(drawHud({ lane: 'bot', cars: [3, 0, 0] }, { linkOk: true })),
    ).toBe(snapshot(GOLDEN_BOT_300));
  });

  it('draws three lane outlines and three empty bars for null, [0, 0, 0]', () => {
    expect(
      toAscii(drawHud({ lane: null, cars: [0, 0, 0] }, { linkOk: true })),
    ).toBe(snapshot(GOLDEN_NULL_000));
  });

  it('renders the stale variant as every pixel >> 1 (050 AC-2)', () => {
    const bright = drawHud({ lane: 'top', cars: [1, 2, 3] }, { linkOk: true });
    const dimmed = drawHud({ lane: 'top', cars: [1, 2, 3] }, { linkOk: false });

    expect(dimmed.length).toBe(bright.length);
    for (let index = 0; index < bright.length; index += 1) {
      expect(dimmed[index]).toBe((bright[index] as number) >> 1);
    }
    expect(toAscii(dimmed)).toBe(snapshot(GOLDEN_TOP_123_DIM));
  });

  it('dithers every filled area and nothing else', () => {
    // `min` sampling drops solid edges to `.` and leaves dithered areas at `+`,
    // so this golden is the map of what the driver sees as a half tone: the
    // called lane and the lit segments.
    expect(
      toAscii(drawHud({ lane: 'top', cars: [1, 2, 3] }, { linkOk: true }), {
        sample: 'min',
      }),
    ).toBe(snapshot(GOLDEN_TOP_123_DITHER));
  });

  it('draws the icons at half the round-1 size along the top edge', () => {
    // Triangles ~30 px tall, the middle a ~40x10 dash.
    expect(LANES.bottomY - LANES.topY).toBe(30);
    expect(LANES.halfWidth * 2).toBe(34);
    expect([LANES.dashWidth, LANES.dashHeight]).toEqual([40, 10]);

    const frame = drawHud({ lane: 'mid', cars: [0, 0, 0] }, { linkOk: true });
    const lit: number[] = [];
    for (let y = 0; y < HUD_HEIGHT; y += 1) {
      if (at(frame, 144, y) > 0) {
        lit.push(y);
      }
    }
    // The dash is the only thing on the centre column above the bars.
    const dash = lit.filter((y) => y < BAR.y);
    expect(dash[0]).toBeGreaterThanOrEqual(LANES.topY);
    expect((dash.at(-1) as number) - (dash[0] as number) + 1).toBe(
      LANES.dashHeight,
    );
  });

  it('fills the called lane with a 2x2 checker on the pixel grid', () => {
    const frame = drawHud({ lane: 'mid', cars: [0, 0, 0] }, { linkOk: true });
    const centre = { x: 144, y: Math.round((LANES.topY + LANES.bottomY) / 2) };

    // Neighbouring pixels alternate: that is the dither, not an average level.
    const here = at(frame, centre.x, centre.y);
    expect(FILL_LEVELS.has(here)).toBe(true);
    expect(at(frame, centre.x + 1, centre.y)).not.toBe(here);
    expect(FILL_LEVELS.has(at(frame, centre.x + 1, centre.y))).toBe(true);
    expect(at(frame, centre.x + 1, centre.y + 1)).toBe(here);
  });

  it('keeps the two uncalled lanes as thin hollow outlines', () => {
    const frame = drawHud({ lane: 'mid', cars: [0, 0, 0] }, { linkOk: true });
    const { outlineLevel, bottomY, topY } = LANES;

    // ▲ on the right: base edge lit, interior empty.
    expect(at(frame, 240, bottomY - 1)).toBe(outlineLevel);
    expect(at(frame, 240, bottomY - 4)).toBe(0);
    // ▼ on the left: top edge lit, interior empty.
    expect(at(frame, 48, topY)).toBe(outlineLevel);
    expect(at(frame, 48, topY + 8)).toBe(0);

    // An uncalled dash is a hollow rectangle too.
    const hollow = drawHud({ lane: 'top', cars: [0, 0, 0] }, { linkOk: true });
    const dashTop = Math.round((topY + bottomY - LANES.dashHeight) / 2);
    expect(at(hollow, 144, dashTop)).toBe(outlineLevel);
    expect(at(hollow, 144, dashTop + LANES.dashHeight / 2)).toBe(0);
  });

  it('puts the lanes in track order: bot left, mid middle, top right', () => {
    expect(LANES.slots.map((slot) => slot.lane)).toEqual(['bot', 'mid', 'top']);
    expect(LANES.slots.map((slot) => slot.centreX)).toEqual([48, 144, 240]);

    // Each call lights its own slot and no other.
    const bot = drawHud({ lane: 'bot', cars: [0, 0, 0] }, { linkOk: true });
    const top = drawHud({ lane: 'top', cars: [0, 0, 0] }, { linkOk: true });
    expect(FILL_LEVELS.has(at(bot, 48, 12))).toBe(true);
    expect(at(bot, 240, 28)).toBe(0);
    expect(FILL_LEVELS.has(at(top, 240, 28))).toBe(true);
    expect(at(top, 48, 12)).toBe(0);
  });

  it('centres one bar under each lane icon, along the bottom edge', () => {
    expect(BAR.xs.map((x) => x + BAR.width / 2)).toEqual([48, 144, 240]);
    expect(BAR.y + BAR.height).toBeLessThanOrEqual(HUD_HEIGHT);
    expect(BAR.y).toBeGreaterThan(LANES.bottomY);
    // Three cells between the walls and two dividers exactly fill the bar.
    expect(
      2 * BAR.outlineThickness +
        3 * BAR.segmentWidth +
        2 * BAR.outlineThickness,
    ).toBe(BAR.width);
  });

  it('fills cars[i] segments of bar i, left to right', () => {
    expect(BAR.fillDirection).toBe('left-to-right');

    for (const level of [0, 1, 2, 3] as const) {
      const frame = drawHud(
        { lane: null, cars: [level, 0, level] },
        { linkOk: true },
      );
      const levels = level === 3 ? ALERT_FILL_LEVELS : FILL_LEVELS;
      for (const barIndex of [0, 2]) {
        for (let cell = 0; cell < 3; cell += 1) {
          const point = segmentCentre(BAR.xs[barIndex] as number, cell);
          const value = at(frame, point.x, point.y);
          if (cell < level) {
            expect(levels.has(value)).toBe(true);
          } else {
            expect(value).toBe(0);
          }
        }
      }
      // The middle bar was 0: hollow, with its dividers still drawn.
      for (let cell = 0; cell < 3; cell += 1) {
        const point = segmentCentre(BAR.xs[1] as number, cell);
        expect(at(frame, point.x, point.y)).toBe(0);
      }
      const divider = BAR.xs[1] + BAR.outlineThickness + BAR.segmentWidth;
      expect(at(frame, divider, BAR.y + BAR.height / 2)).toBe(BAR.outlineLevel);
    }
  });

  it('gives a bar at level 3 the bright alert outline (050 AC-2)', () => {
    const frame = drawHud({ lane: null, cars: [2, 3, 0] }, { linkOk: true });
    const outline = (barIndex: number): number =>
      at(frame, (BAR.xs[barIndex] as number) + 10, BAR.y);

    expect(outline(0)).toBe(BAR.outlineLevel);
    expect(outline(1)).toBe(BAR.alertOutlineLevel);
    expect(outline(2)).toBe(BAR.outlineLevel);
    const alertCell = segmentCentre(BAR.xs[1] as number, 0);
    expect(ALERT_FILL_LEVELS.has(at(frame, alertCell.x, alertCell.y))).toBe(
      true,
    );
    const normalCell = segmentCentre(BAR.xs[0] as number, 0);
    expect(FILL_LEVELS.has(at(frame, normalCell.x, normalCell.y))).toBe(true);
  });
});
