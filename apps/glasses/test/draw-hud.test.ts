function snapshot(text: string): string {
  return text.replace(/^\n/, '');
}

function at(frame: Uint8Array, x: number, y: number): number {
  return frame[y * STRIP_WIDTH + x] as number;
}

/** Levels a dithered area may hold: the checker's two phases. */
const FILL_LEVELS = new Set<number>([DESIGN.fill.on, DESIGN.fill.off]);
const ALERT_FILL_LEVELS = new Set<number>([
  DESIGN.alertFill.on,
  DESIGN.alertFill.off,
]);

const { cars: BAR, lanes: LANES } = DESIGN;
const SEAM = HALF_WIDTH;
const ON = { linkOk: true };
const OFF = { linkOk: false };

/** A pixel in the middle of segment `cell` (0..2) of the bar at `barX`. */
function segmentCentre(
  barX: number,
  cell: number,
): { readonly x: number; readonly y: number } {
  const wall = BAR.outlineThickness;
  return {
    x:
      barX +
      wall +
      cell * (BAR.segmentWidth + wall) +
      Math.floor(BAR.segmentWidth / 2),
    y: BAR.y + Math.floor(BAR.height / 2),
  };
}

/** Re-joins two halves row by row — the inverse of `splitStrip`. */
function join(left: Uint8Array, right: Uint8Array): Uint8Array {
  const strip = new Uint8Array(left.length + right.length);
  for (let y = 0; y < STRIP_HEIGHT; y += 1) {
    strip.set(
      left.subarray(y * HALF_WIDTH, (y + 1) * HALF_WIDTH),
      y * STRIP_WIDTH,
    );
    strip.set(
      right.subarray(y * HALF_WIDTH, (y + 1) * HALF_WIDTH),
      y * STRIP_WIDTH + HALF_WIDTH,
    );
  }
  return strip;
}

describe('HUD strips (050 AC-1)', () => {
  it('fills exactly 576x48 bytes of 0..15 per strip', () => {
    for (const frame of [
      drawTopStrip('mid', ON),
      drawBottomStrip([1, 2, 3], ON),
    ]) {
      expect(frame).toBeInstanceOf(Uint8Array);
      expect(frame.length).toBe(576 * 48);
      expect(Math.max(...frame)).toBeLessThanOrEqual(15);
    }
    expect([STRIP_WIDTH, STRIP_HEIGHT, HALF_WIDTH]).toEqual([576, 48, 288]);
  });

  it('draws ▲ filled in the top-right corner for lane top', () => {
    expect(toAscii(drawTopStrip('top', ON))).toBe(snapshot(TOP_TOP));
  });

  it('draws the dash filled on the seam for lane mid', () => {
    expect(toAscii(drawTopStrip('mid', ON))).toBe(snapshot(TOP_MID));
  });

  it('draws ▼ filled in the top-left corner for lane bot', () => {
    expect(toAscii(drawTopStrip('bot', ON))).toBe(snapshot(TOP_BOT));
  });

  it('draws three lane outlines for lane null', () => {
    expect(toAscii(drawTopStrip(null, ON))).toBe(snapshot(TOP_NULL));
  });

  it('draws bars 1 / 2 / 3 at left corner / seam / right corner for [1, 2, 3]', () => {
    expect(toAscii(drawBottomStrip([1, 2, 3], ON))).toBe(snapshot(BOTTOM_123));
  });

  it('draws three empty bars for [0, 0, 0]', () => {
    expect(toAscii(drawBottomStrip([0, 0, 0], ON))).toBe(snapshot(BOTTOM_000));
  });

  it('draws a full alert bar in the bottom-left corner for [3, 0, 0]', () => {
    expect(toAscii(drawBottomStrip([3, 0, 0], ON))).toBe(snapshot(BOTTOM_300));
  });

  it('renders the stale variant of every strip as every pixel >> 1 (050 AC-2)', () => {
    const cases = [
      [drawTopStrip('top', ON), drawTopStrip('top', OFF)],
      [drawBottomStrip([1, 2, 3], ON), drawBottomStrip([1, 2, 3], OFF)],
    ] as const;

    for (const [bright, dimmed] of cases) {
      expect(dimmed.length).toBe(bright.length);
      for (let index = 0; index < bright.length; index += 1) {
        expect(dimmed[index]).toBe((bright[index] as number) >> 1);
      }
    }
    expect(toAscii(drawTopStrip('top', OFF))).toBe(snapshot(TOP_TOP_DIM));
    expect(toAscii(drawBottomStrip([1, 2, 3], OFF))).toBe(
      snapshot(BOTTOM_123_DIM),
    );
  });

  it('dims all four image containers when the link is down', () => {
    const bright = drawStrips({ lane: 'mid', cars: [1, 2, 3] }, ON);
    const dimmed = drawStrips({ lane: 'mid', cars: [1, 2, 3] }, OFF);

    for (const strip of ['top', 'bottom'] as const) {
      const brightHalves = splitStrip(bright[strip]);
      const dimHalves = splitStrip(dimmed[strip]);
      for (const half of [0, 1] as const) {
        const expected = (brightHalves[half] as Uint8Array).map((v) => v >> 1);
        expect(dimHalves[half]).toEqual(expected);
        // Every container has something lit, so every one of them changes.
        expect(dimHalves[half]).not.toEqual(brightHalves[half]);
      }
    }
  });

  it('dithers every filled area and nothing else', () => {
    // `min` sampling drops solid edges to `.` and leaves dithered areas at `+`,
    // so these goldens are the map of what the driver sees as a half tone: the
    // called lane and the lit segments.
    expect(toAscii(drawTopStrip('top', ON), { sample: 'min' })).toBe(
      snapshot(TOP_TOP_DITHER),
    );
    expect(toAscii(drawBottomStrip([1, 2, 3], ON), { sample: 'min' })).toBe(
      snapshot(BOTTOM_123_DITHER),
    );
  });
});

describe('splitStrip (the seam at x 288)', () => {
  it('cuts a strip into two 288x48 halves that re-join byte for byte', () => {
    const strips = [
      ...(['top', 'mid', 'bot', null] as const).map((lane) =>
        drawTopStrip(lane, ON),
      ),
      drawBottomStrip([1, 2, 3], ON),
      drawBottomStrip([3, 3, 3], OFF),
    ];

    for (const strip of strips) {
      const [left, right] = splitStrip(strip);
      expect(left.length).toBe(HALF_PIXELS);
      expect(right.length).toBe(HALF_PIXELS);
      expect(HALF_PIXELS).toBe(288 * 48);
      expect(join(left, right)).toEqual(strip);
    }
  });

  it('puts column 287 in the left half and column 288 in the right half', () => {
    const strip = new Uint8Array(STRIP_WIDTH * STRIP_HEIGHT);
    for (let y = 0; y < STRIP_HEIGHT; y += 1) {
      strip[y * STRIP_WIDTH + SEAM - 1] = 7;
      strip[y * STRIP_WIDTH + SEAM] = 9;
    }

    const [left, right] = splitStrip(strip);
    for (let y = 0; y < STRIP_HEIGHT; y += 1) {
      expect(left[y * HALF_WIDTH + HALF_WIDTH - 1]).toBe(7);
      expect(right[y * HALF_WIDTH]).toBe(9);
    }
  });

  it('draws the dash and the middle bar across the seam, half in each image', () => {
    const [dashLeft, dashRight] = splitStrip(drawTopStrip('mid', ON));
    const dashRow = Math.round((LANES.topY + LANES.bottomY) / 2);
    expect(
      FILL_LEVELS.has(dashLeft[dashRow * HALF_WIDTH + HALF_WIDTH - 1]!),
    ).toBe(true);
    expect(FILL_LEVELS.has(dashRight[dashRow * HALF_WIDTH]!)).toBe(true);

    const [barLeft, barRight] = splitStrip(drawBottomStrip([0, 0, 0], ON));
    expect(barLeft[BAR.y * HALF_WIDTH + HALF_WIDTH - 1]).toBe(BAR.outlineLevel);
    expect(barRight[BAR.y * HALF_WIDTH]).toBe(BAR.outlineLevel);
  });

  it('rejects a buffer that is not a whole strip', () => {
    expect(() => splitStrip(new Uint8Array(10))).toThrow(/does not split/);
  });
});

describe('HUD design', () => {
  it('keeps the round-3 icon size: triangles 30x34, the dash 40x10', () => {
    expect(LANES.bottomY - LANES.topY).toBe(30);
    expect(LANES.halfWidth * 2).toBe(34);
    expect([LANES.dashWidth, LANES.dashHeight]).toEqual([40, 10]);
    expect(LANES.bottomY).toBeLessThan(STRIP_HEIGHT);

    const frame = drawTopStrip('mid', ON);
    const lit: number[] = [];
    for (let y = 0; y < STRIP_HEIGHT; y += 1) {
      if (at(frame, SEAM, y) > 0) {
        lit.push(y);
      }
    }
    expect(lit[0]).toBeGreaterThanOrEqual(LANES.topY);
    expect((lit.at(-1) as number) - (lit[0] as number) + 1).toBe(
      LANES.dashHeight,
    );
  });

  it('fills the called lane with a 2x2 checker on the pixel grid', () => {
    const frame = drawTopStrip('mid', ON);
    const centre = { x: SEAM, y: Math.round((LANES.topY + LANES.bottomY) / 2) };

    const here = at(frame, centre.x, centre.y);
    expect(FILL_LEVELS.has(here)).toBe(true);
    expect(at(frame, centre.x + 1, centre.y)).not.toBe(here);
    expect(FILL_LEVELS.has(at(frame, centre.x + 1, centre.y))).toBe(true);
    expect(at(frame, centre.x + 1, centre.y + 1)).toBe(here);
  });

  it('keeps the two uncalled lanes as thin hollow outlines', () => {
    const frame = drawTopStrip('mid', ON);
    const { outlineLevel, bottomY, topY } = LANES;
    const [bot, , top] = LANES.slots.map((slot) => slot.centreX);

    expect(at(frame, top!, bottomY - 1)).toBe(outlineLevel);
    expect(at(frame, top!, bottomY - 4)).toBe(0);
    expect(at(frame, bot!, topY)).toBe(outlineLevel);
    expect(at(frame, bot!, topY + 8)).toBe(0);

    const hollow = drawTopStrip('top', ON);
    const dashTop = Math.round((topY + bottomY - LANES.dashHeight) / 2);
    expect(at(hollow, SEAM, dashTop)).toBe(outlineLevel);
    expect(at(hollow, SEAM, dashTop + LANES.dashHeight / 2)).toBe(0);
  });

  it('puts the lanes in track order: ▼ top-left corner, ▬ on the seam, ▲ top-right corner', () => {
    expect(LANES.slots.map((slot) => slot.lane)).toEqual(['bot', 'mid', 'top']);
    expect(LANES.slots.map((slot) => slot.centreX)).toEqual([51, 288, 525]);
    // The corner icons sit wholly inside their own image container.
    const [bot, , top] = LANES.slots.map((slot) => slot.centreX);
    expect(bot! + LANES.halfWidth).toBeLessThan(SEAM);
    expect(top! - LANES.halfWidth).toBeGreaterThanOrEqual(SEAM);
    // Mirror-symmetric about the seam.
    expect(bot! + top!).toBe(STRIP_WIDTH);

    const botFrame = drawTopStrip('bot', ON);
    const topFrame = drawTopStrip('top', ON);
    expect(FILL_LEVELS.has(at(botFrame, bot!, 17))).toBe(true);
    expect(at(botFrame, top!, 33)).toBe(0);
    expect(FILL_LEVELS.has(at(topFrame, top!, 33))).toBe(true);
    expect(at(topFrame, bot!, 17)).toBe(0);
  });

  it('puts one bar in each bottom corner and one on the seam, under its lane icon', () => {
    expect(BAR.xs.map((x) => x + BAR.width / 2)).toEqual(
      LANES.slots.map((slot) => slot.centreX),
    );
    expect(BAR.xs[0]! + BAR.width).toBeLessThanOrEqual(SEAM);
    expect(BAR.xs[1]).toBeLessThan(SEAM);
    expect(BAR.xs[1]! + BAR.width).toBeGreaterThan(SEAM);
    expect(BAR.xs[2]).toBeGreaterThanOrEqual(SEAM);
    expect(BAR.xs[2]! + BAR.width).toBeLessThanOrEqual(STRIP_WIDTH);
    expect(BAR.y + BAR.height).toBeLessThanOrEqual(STRIP_HEIGHT);
    expect(
      2 * BAR.outlineThickness +
        3 * BAR.segmentWidth +
        2 * BAR.outlineThickness,
    ).toBe(BAR.width);
  });

  it('fills cars[i] segments of bar i, left to right', () => {
    expect(BAR.fillDirection).toBe('left-to-right');

    for (const level of [0, 1, 2, 3] as const) {
      const frame = drawBottomStrip([level, 0, level], ON);
      const levels = level === 3 ? ALERT_FILL_LEVELS : FILL_LEVELS;
      for (const barIndex of [0, 2]) {
        for (let cell = 0; cell < 3; cell += 1) {
          const point = segmentCentre(BAR.xs[barIndex] as number, cell);
          const value = at(frame, point.x, point.y);
          if (cell < level) {
            expect(levels.has(value)).toBe(true);
          } else {
            expect(value).toBe(0);
          }
        }
      }
      for (let cell = 0; cell < 3; cell += 1) {
        const point = segmentCentre(BAR.xs[1] as number, cell);
        expect(at(frame, point.x, point.y)).toBe(0);
      }
      const divider = BAR.xs[1] + BAR.outlineThickness + BAR.segmentWidth;
      expect(at(frame, divider, BAR.y + BAR.height / 2)).toBe(BAR.outlineLevel);
    }
  });

  it('gives a bar at level 3 the bright alert outline (050 AC-2)', () => {
    const frame = drawBottomStrip([2, 3, 0], ON);
    const outline = (barIndex: number): number =>
      at(frame, (BAR.xs[barIndex] as number) + 10, BAR.y);

    expect(outline(0)).toBe(BAR.outlineLevel);
    expect(outline(1)).toBe(BAR.alertOutlineLevel);
    expect(outline(2)).toBe(BAR.outlineLevel);
    const alertCell = segmentCentre(BAR.xs[1] as number, 0);
    expect(ALERT_FILL_LEVELS.has(at(frame, alertCell.x, alertCell.y))).toBe(
      true,
    );
    const normalCell = segmentCentre(BAR.xs[0] as number, 0);
    expect(FILL_LEVELS.has(at(frame, normalCell.x, normalCell.y))).toBe(true);
  });
});
