/** A pixel in the middle of segment `index` (0 = bottom) of the left ring. */
function ringCentre(
  side: 'left' | 'right',
  index: number,
): { readonly x: number; readonly y: number } {
  const segment = cornerSegments(side)[index]!;
  const angle = (((segment.startAngle + segment.endAngle) / 2) * Math.PI) / 180;
  const radius = (segment.innerRadius + segment.outerRadius) / 2;
  return {
    x: Math.floor(segment.centre.x + radius * Math.cos(angle)),
    y: Math.floor(segment.centre.y - radius * Math.sin(angle)),
  };
}

/** A pixel in the middle of segment `index` (0 = bottom) of the middle bar. */
function middleCentre(index: number): {
  readonly x: number;
  readonly y: number;
} {
  const segment = middleSegments()[index]!;
  return {
    x: segment.x + Math.floor(segment.width / 2),
    y: segment.y + Math.floor(segment.height / 2),
  };
}

/** Re-joins two halves row by row — the inverse of `splitStrip`. */
function join(left: Uint8Array, right: Uint8Array): Uint8Array {
  const height = left.length / HALF_WIDTH;
  const strip = new Uint8Array(left.length + right.length);
  for (let y = 0; y < height; y += 1) {
    strip.set(
      left.subarray(y * HALF_WIDTH, (y + 1) * HALF_WIDTH),
      y * STRIP_WIDTH,
    );
    strip.set(
      right.subarray(y * HALF_WIDTH, (y + 1) * HALF_WIDTH),
      y * STRIP_WIDTH + HALF_WIDTH,
    );
  }
  return strip;
}

/** Lit pixels of a strip in the column range [x0, x1). */
function litBox(
  frame: Uint8Array,
  height: number,
  x0: number,
  x1: number,
): { minX: number; maxX: number; minY: number; maxY: number } {
  const box = {
    minX: Infinity,
    maxX: -Infinity,
    minY: Infinity,
    maxY: -Infinity,
  };
  for (let y = 0; y < height; y += 1) {
    for (let x = x0; x < x1; x += 1) {
      if (at(frame, x, y) > 0) {
        box.minX = Math.min(box.minX, x);
        box.maxX = Math.max(box.maxX, x);
        box.minY = Math.min(box.minY, y);
        box.maxY = Math.max(box.maxY, y);
      }
    }
  }
  return box;
}

